public class Operators2{
    public static void main(String args[]){
        int a = 10;
        int b = 5;
        //Here we are seeing -- Relational operators 
        //1
        if( a == b){
            System.out.println("good");
        }
        //2
        if(a != b){
            System.out.println("good");
        }
        //3
        if( a > b){
            System.out.println("good");
        }
        //4
        if( a < b){
            System.out.println("good");
        }
        //5
        if( a >= b){
            System.out.println("good");
        }
        //6
        if( a <= b){
            System.out.println("good");
        }
    }
}