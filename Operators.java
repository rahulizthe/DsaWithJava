public class Operators {
    public static void main(String args[]){
        int a = 10;
        int b = 5;
        //Here we are seeing -- Logical operators 
        //1
        if( a ==10 && b==5){
            System.out.println("good");
        }
        //2
        if(a==10 || b==5){
            System.out.println("good");
        }
        //3
        if( !(a!=5 && b!=10)){
            System.out.println("good");
        }
    }
}
