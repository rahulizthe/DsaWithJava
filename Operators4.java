public class Operators4 {
    public static void main(String args[]) {

        int a = 5;
        int b = 3;
        //Here are we seeing --Bitwise Operators
        //1
        System.out.println("a & b = " + (a & b));
        //2
        System.out.println("a | b = " + (a | b));
        //3
        System.out.println("a ^ b = " + (a ^ b));
        //4
        System.out.println("~a = " + (~a));
        //5
        System.out.println("a << 1 = " + (a << 1));
        //6
        System.out.println("a >> 1 = " + (a >> 1));
        //7
        System.out.println("a >>> 1 = " + (a >>> 1));
    }
}